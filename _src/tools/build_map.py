"""
Bake Zimbabwe's national border and 10 provinces into SVG paths for the site map.

Source: geoBoundaries gbOpen ZWE ADM0 / ADM1 (simplified), from ZIMSTAT / OCHA ROSEA.
Usage:  python build_map.py <adm0.geojson> <adm1.geojson> <out.js>
Output: window.GW_GEO = { w, h, proj: {lon0, lat0, kx, ky, pad}, outline, provinces: [...] }
"""
import json, math, sys

LON0, LAT0 = 25.2, -15.55           # top-left of the projected frame
KY = 96.0                           # px per degree of latitude
KX = KY * math.cos(math.radians(19.0))  # equirectangular, corrected at Zimbabwe's mid-latitude
PAD = 40
TOL = 0.55                          # Douglas-Peucker tolerance in px

def proj(lon, lat):
    return (PAD + (lon - LON0) * KX, PAD + (LAT0 - lat) * KY)

def dp(pts, tol):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1e-9
    i, dmax = 0, -1
    for k in range(1, len(pts) - 1):
        d = abs(dy * pts[k][0] - dx * pts[k][1] + x2 * y1 - y2 * x1) / L
        if d > dmax:
            i, dmax = k, d
    if dmax <= tol:
        return [pts[0], pts[-1]]
    return dp(pts[:i + 1], tol)[:-1] + dp(pts[i:], tol)

def rings(geom):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    return [poly[0] for poly in polys]  # outer rings only

def to_path(ring):
    pts = [proj(*c) for c in ring[:-1]]  # drop closing point; a closed ring collapses in DP
    h = len(pts) // 2
    pts = dp(pts[:h + 1], TOL)[:-1] + dp(pts[h:], TOL)
    return 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in pts) + 'Z', pts

def centroid(pts):
    a = cx = cy = 0
    for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
        f = x0 * y1 - x1 * y0
        a += f; cx += (x0 + x1) * f; cy += (y0 + y1) * f
    a *= 0.5
    return (cx / (6 * a), cy / (6 * a)) if a else pts[0]

adm0, adm1, out = sys.argv[1:4]
nat = json.load(open(adm0, encoding='utf8'))['features'][0]['geometry']
outline, outline_pts = [], []
for r in rings(nat):
    d, pts = to_path(r)
    if len(pts) > 8:
        outline.append(d); outline_pts.append([[round(x, 1), round(y, 1)] for x, y in pts])

provinces = []
for ft in json.load(open(adm1, encoding='utf8'))['features']:
    name = ft['properties']['shapeName']
    best = max(rings(ft['geometry']), key=len)
    d, pts = to_path(best)
    cx, cy = centroid(pts)
    provinces.append({'name': name, 'd': d, 'cx': round(cx, 1), 'cy': round(cy, 1)})

xs = [p[0] for ring in outline_pts for p in ring]; ys = [p[1] for ring in outline_pts for p in ring]
data = {
    'w': round(max(xs) + PAD), 'h': round(max(ys) + PAD),
    'proj': {'lon0': LON0, 'lat0': LAT0, 'kx': round(KX, 4), 'ky': KY, 'pad': PAD},
    'outline': ' '.join(outline), 'ring': outline_pts[0], 'provinces': provinces,
}
with open(out, 'w', encoding='utf8') as f:
    f.write('/* Generated by _src/tools/build_map.py from geoBoundaries ZWE (ZIMSTAT / OCHA ROSEA). Do not edit. */\n')
    f.write('window.GW_GEO = ' + json.dumps(data, separators=(',', ':')) + ';\n')
print('outline pts', sum(len(r) for r in outline_pts), 'provinces', len(provinces), 'size', data['w'], data['h'])
